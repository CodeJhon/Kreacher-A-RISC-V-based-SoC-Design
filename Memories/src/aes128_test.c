static const uint8_t rcon[10] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36};

static inline uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80u) ? 0x1bu : 0)); }
static inline uint8_t mul2(uint8_t x) { return xtime(x); }
static inline uint8_t mul3(uint8_t x) { return (uint8_t)(xtime(x) ^ x); }

static void sub_bytes(uint8_t st[16]) { for (uint32_t i = 0; i < 16; i++) st[i] = sbox[st[i]]; }

static void shift_rows(uint8_t st[16]) {
    uint8_t t;
    t = st[1];  st[1]  = st[5];  st[5]  = st[9];  st[9]  = st[13]; st[13] = t;
    t = st[2];  st[2]  = st[10]; st[10] = t;
    t = st[6];  st[6]  = st[14]; st[14] = t;
    t = st[15]; st[15] = st[11]; st[11] = st[7];  st[7]  = st[3];  st[3]  = t;
}

static void mix_columns(uint8_t st[16]) {
    for (uint32_t c = 0; c < 4; c++) {
        uint32_t i = c * 4;
        uint8_t a0 = st[i+0], a1 = st[i+1], a2 = st[i+2], a3 = st[i+3];
        st[i+0] = (uint8_t)(mul2(a0) ^ mul3(a1) ^ a2 ^ a3);
        st[i+1] = (uint8_t)(a0 ^ mul2(a1) ^ mul3(a2) ^ a3);
        st[i+2] = (uint8_t)(a0 ^ a1 ^ mul2(a2) ^ mul3(a3));
        st[i+3] = (uint8_t)(mul3(a0) ^ a1 ^ a2 ^ mul2(a3));
    }
}

static void add_round_key(uint8_t st[16], const uint8_t *rk) {
    for (uint32_t i = 0; i < 16; i++) st[i] ^= rk[i];
}

static void key_expansion(const uint8_t key[16], uint8_t round_keys[176]) {
    for (uint32_t i = 0; i < 16; i++) round_keys[i] = key[i];

    uint32_t bytes_generated = 16, rcon_idx = 0;
    uint8_t temp[4];

    while (bytes_generated < 176) {
        for (uint32_t i = 0; i < 4; i++) temp[i] = round_keys[bytes_generated - 4 + i];

        if ((bytes_generated & 15u) == 0) {
            uint8_t t = temp[0];
            temp[0] = sbox[temp[1]] ^ rcon[rcon_idx++];
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[t];
        }

        for (uint32_t i = 0; i < 4; i++) {
            round_keys[bytes_generated] = round_keys[bytes_generated - 16] ^ temp[i];
            bytes_generated++;
        }
    }
}

static void aes128_encrypt_block(uint8_t st[16], const uint8_t round_keys[176]) {
    add_round_key(st, &round_keys[0]);
    for (uint32_t round = 1; round <= 9; round++) {
        sub_bytes(st);
        shift_rows(st);
        mix_columns(st);
        add_round_key(st, &round_keys[round * 16]);
    }
    sub_bytes(st);
    shift_rows(st);
    add_round_key(st, &round_keys[160]);
}

static uint32_t signature_test(void) {
    static uint8_t key[16], pt[16], st[16], round_keys[176];

    for (uint32_t i = 0; i < 16; i++) {
        key[i] = (uint8_t)(i * 17u + 3u);
        pt[i]  = (uint8_t)(i * 29u + 11u);
        st[i]  = pt[i];
    }

    key_expansion(key, round_keys);
    aes128_encrypt_block(st, round_keys);

#if !defined(__riscv)
    printf("AES-128 ciphertext:\n");
    for (uint32_t i = 0; i < 16; i++) {
        printf("%02x", st[i]);
        if ((i & 3u) == 3u) printf(" ");
    }
    printf("\n");
#endif

    uint64_t acc = 0x510e527fade682d1ULL;
    for (uint32_t i = 0; i < 176; i++) {
        acc ^= (uint64_t)round_keys[i];
        acc += ((uint64_t)round_keys[i] << (i & 7u));
    }
    for (uint32_t i = 0; i < 16; i++) {
        acc ^= (uint64_t)st[i];
        if (st[i] & 1u) acc ^= 0x1111u;
        else            acc += 0x2222u;

        switch (i & 3u) {
            case 0: acc += 0x11111111ULL; break;
            case 1: acc ^= 0x22222222ULL; break;
            case 2: acc -= 0x33333333ULL; break;
            default: acc ^= (acc >> 5);   break;
        }
    }

    return (uint32_t)(acc ^ (acc >> 32));
}

